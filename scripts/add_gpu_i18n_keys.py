def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f, object_pairs_hook=collections.OrderedDict)

def main():
    en = load(EN)
    ko = load(KO)
    added = []
    for key, (en_val, ko_val) in NEW.items():
        if key in en:
            sys.exit(f"ABORT: duplicate key already in en.json: {key}")
        if key in ko:
            sys.exit(f"ABORT: duplicate key already in ko.json: {key}")
        en[key] = en_val
        ko[key] = ko_val
        added.append(key)
    # ko must cover all en keys
    missing = [k for k in en if k not in ko]
    if missing:
        sys.exit(f"ABORT: ko missing {len(missing)} keys, e.g. {missing[:3]}")
    for path, data in ((EN, en), (KO, ko)):
        text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"added {len(added)} keys; en={len(en)} ko={len(ko)} (parity ok)")

if __name__ == "__main__":
    main()
